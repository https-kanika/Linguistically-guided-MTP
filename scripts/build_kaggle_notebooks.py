"""Build self-contained Kaggle notebooks from src/lgmtp (PLAN rule 1(a), §4).

    python scripts/build_kaggle_notebooks.py 01     # -> kaggle/01_traces_v2.ipynb
    python scripts/build_kaggle_notebooks.py 03     # -> kaggle/03_real_loop.ipynb (step S5)

The first code cell writes the lgmtp modules into /kaggle/working/lgmtp/ and imports them, so the
user uploads a single .ipynb. src/lgmtp stays the single source of truth: never edit kaggle/*.ipynb.
Records the git HEAD hash (+ "-dirty" if the tree has uncommitted changes) and a sha256 of the
inlined sources, so results can be traced to code even without a commit.
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

import nbformat as nbf

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "lgmtp"
OUT = ROOT / "kaggle"

TRANSFORMERS_PIN = "5.22.1"   # version used by scripts/smoke_cpu.py

MODULES = {
    "01": ["__init__", "boundaries", "vocab", "traces", "gpu_traces"],
    "03": ["__init__", "boundaries", "vocab", "traces", "gpu_traces", "simulator", "policies", "morph",
           "stats", "tuning", "spec_loop"],
}
RES = ROOT / "results" / "phase1"
EMBED_LIMIT = 5 * 1024 * 1024   # PLAN §4: larger artifacts go to a private Kaggle Dataset instead


def git_hash() -> str:
    try:
        h = subprocess.check_output(["git", "rev-parse", "--short=12", "HEAD"], cwd=ROOT, text=True).strip()
        dirty = subprocess.check_output(["git", "status", "--porcelain", "--", "src", "scripts"],
                                        cwd=ROOT, text=True).strip()
        return h + ("-dirty" if dirty else "")
    except Exception:  # noqa: BLE001
        return "nogit"


def sources(names) -> dict[str, str]:
    return {n: (SRC / f"{n}.py").read_text(encoding="utf-8") for n in names}


def inline_cell(srcs: dict[str, str], build_id: str) -> str:
    lines = [
        "# === lgmtp source, generated by scripts/build_kaggle_notebooks.py: DO NOT EDIT ===",
        "import os, sys, importlib",
        "os.environ.setdefault('PYTORCH_CUDA_ALLOC_CONF', 'expandable_segments:True')",
        "PKG = '/kaggle/working/lgmtp' if os.path.isdir('/kaggle/working') else os.path.abspath('lgmtp')",
        "os.makedirs(PKG, exist_ok=True)",
        "LGMTP_SOURCES = {",
    ]
    for n, s in srcs.items():
        lines.append(f"    {n!r}: {s!r},")
    lines += [
        "}",
        "for _n, _s in LGMTP_SOURCES.items():",
        "    with open(os.path.join(PKG, _n + '.py'), 'w', encoding='utf-8') as _f:",
        "        _f.write(_s)",
        "sys.path.insert(0, os.path.dirname(PKG))",
        "for _m in [m for m in list(sys.modules) if m == 'lgmtp' or m.startswith('lgmtp.')]:",
        "    del sys.modules[_m]",
        "import lgmtp",
        f"LGMTP_BUILD = {build_id!r}",
        "print('lgmtp build', LGMTP_BUILD)",
    ]
    return "\n".join(lines)


def build_01() -> Path:
    srcs = sources(MODULES["01"])
    sha = hashlib.sha256("".join(srcs[n] for n in sorted(srcs)).encode()).hexdigest()[:12]
    gh = git_hash()
    build_id = f"git={gh} src_sha256={sha}"

    md = nbf.v4.new_markdown_cell
    code = nbf.v4.new_code_cell
    nb = nbf.v4.new_notebook()
    nb.cells = [
        md(f"""# 01 - Traces v2 (8B target outputs, teacher-forced draft + target passes, timing)

**Generated by `scripts/build_kaggle_notebooks.py` ({build_id}). Do not edit; change `src/lgmtp/` and rebuild.**

**Kaggle settings (right sidebar):** Accelerator = **GPU T4 x2**, Internet = **On**, Add-ons > Secrets: **`HF_TOKEN`** (access to `Meta-Llama-3-8B-Instruct`, `Llama-3.2-1B-Instruct`, `openlanguagedata/flores_plus`).

**How to run:** set `SPLIT` in the CONFIG cell (`"dev"` first, then `"devtest"`), then *Save Version > Save & Run All (Commit)*. One split per run.

**Outputs:** `/kaggle/working/traces_v2_<SPLIT>.zip`, to be unzipped into `data/traces_v2/` in the repo. The last cell prints exactly what to download.

**If a run dies:** partial results are saved after every batch / every 50 sentences in `/kaggle/working/traces_v2_<SPLIT>/`. Add that failed version's output as an input to the notebook and set `RESUME_FROM` to its `/kaggle/input/...` path. Then it continues where it stopped."""),
        code(f"!pip -q install -U \"transformers=={TRANSFORMERS_PIN}\" accelerate datasets huggingface_hub"),
        code(inline_cell(srcs, build_id)),
        md("## CONFIG"),
        code(f"""CONFIG = dict(
    SPLIT="dev",          # "dev" (tuning set, 997 sentences) or "devtest" (test set, 1012). One split per run.
    N=None,               # None = whole split; e.g. 20 for a quick check
    BATCH=16,             # lower to 8 if generation runs out of memory
    MAX_NEW=256,
    SMOKE=False,
    TARGET="meta-llama/Meta-Llama-3-8B-Instruct",
    DRAFT="meta-llama/Llama-3.2-1B-Instruct",
    MAX_MEMORY={{0: "8GiB", 1: "10GiB"}},
    OUT_ROOT="/kaggle/working",
    RESUME_FROM=None,     # e.g. "/kaggle/input/<earlier-version-output>" to continue a dead run
    GIT_HASH=LGMTP_BUILD,
)"""),
        code("""from huggingface_hub import login
try:
    from kaggle_secrets import UserSecretsClient
    login(UserSecretsClient().get_secret("HF_TOKEN"))
    print("Logged in with Kaggle secret HF_TOKEN")
except Exception as e:
    print(f"Kaggle secret HF_TOKEN not available ({e})")
    login()
import torch, transformers
print("torch", torch.__version__, "| transformers", transformers.__version__)"""),
        code("from lgmtp.gpu_traces import notebook01_main\nRESULT = notebook01_main(CONFIG)"),
    ]
    nb.metadata.update({
        "kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"},
        "lgmtp_build": build_id,
    })
    OUT.mkdir(exist_ok=True)
    path = OUT / "01_traces_v2.ipynb"
    nbf.write(nb, path)
    print("wrote", path, "|", build_id)
    return path


def real_loop_ids(n: int = 100, seed: int = 0) -> list[int]:
    """Fixed list of devtest ids for the real loop, saved once to results/phase1/real_loop_ids.json."""
    import json
    path = RES / "real_loop_ids.json"
    if path.exists():
        return json.loads(path.read_text())["ids"]
    import numpy as np
    sys.path.insert(0, str(ROOT / "src"))
    from lgmtp.traces import load_traces
    traces, _ = load_traces(ROOT / "data" / "traces_v2" / "traces_devtest.npz")
    all_ids = sorted(t.id for t in traces)
    ids = sorted(int(i) for i in np.random.default_rng(seed).choice(all_ids, n, replace=False))
    path.write_text(json.dumps(dict(ids=ids, seed=seed, n=n, source="devtest ids, rng(0).choice"), indent=1))
    return ids


def build_03() -> Path:
    import base64
    import json
    sel_path, pm_path = RES / "selected_params.json", RES / "prefix_model.pkl.gz"
    for f in (sel_path, pm_path):
        if not f.exists():
            sys.exit(f"missing {f}: run notebooks/02_policies_v2.ipynb first (T7)")
    selected = json.loads(sel_path.read_text(encoding="utf-8"))["selected"]
    ids = real_loop_ids()
    pm_bytes = pm_path.read_bytes()          # already gzip-compressed pickle of the model state
    srcs = sources(MODULES["03"])
    sha = hashlib.sha256(("".join(srcs[n] for n in sorted(srcs))).encode() + pm_bytes
                         + sel_path.read_bytes()).hexdigest()[:12]
    build_id = f"git={git_hash()} src+artifacts_sha256={sha}"
    if len(pm_bytes) * 4 / 3 > EMBED_LIMIT:
        art = OUT / "artifacts"
        art.mkdir(parents=True, exist_ok=True)
        (art / "prefix_model.pkl.gz").write_bytes(pm_bytes)
        pm_cell = ("import gzip, pickle\n"
                   "PREFIX_MODEL_STATE = pickle.load(gzip.open(ARTIFACT_DIR + '/prefix_model.pkl.gz', 'rb'))")
        dataset_note = ("\n\n**Artifacts dataset needed:** upload the folder `kaggle/artifacts/` as a private Kaggle "
                        "Dataset, add it to this notebook, and set `ARTIFACT_DIR` in the CONFIG cell to its "
                        "`/kaggle/input/...` path.")
    else:
        b64 = base64.b64encode(pm_bytes).decode()
        pm_cell = ("import base64, gzip, io, pickle\n"
                   f"_PM_B64 = {b64!r}\n"
                   "PREFIX_MODEL_STATE = pickle.load(gzip.open(io.BytesIO(base64.b64decode(_PM_B64)), 'rb'))\n"
                   "print('prefix model levels:', {k: len(v) for k, v in PREFIX_MODEL_STATE['tot'].items()})")
        dataset_note = ""

    md = nbf.v4.new_markdown_cell
    code = nbf.v4.new_code_cell
    nb = nbf.v4.new_notebook()
    nb.cells = [
        md(f"""# 03 - Real draft-and-verify loop (8B target, 1B draft, batch size 1)

**Generated by `scripts/build_kaggle_notebooks.py` ({build_id}). Do not edit; change `src/lgmtp/` and rebuild.**

Embedded: the dev-selected parameters of every policy (`results/phase1/selected_params.json`), the causal morpheme prefix model (`results/phase1/prefix_model.pkl.gz`), and the fixed list of {len(ids)} devtest ids (`results/phase1/real_loop_ids.json`).{dataset_note}

**Kaggle settings:** Accelerator = **GPU T4 x2**, Internet = **On**, Secret **`HF_TOKEN`**.
**Run:** *Save Version > Save & Run All (Commit)*. After the first 5 sentences the log prints `ESTIMATE: ...`; if it is too long, stop, lower `N_SENT` / `REPEATS` in CONFIG and rerun.
**Output:** `/kaggle/working/real_loop.zip`, to be unzipped into `data/real_loop/` in the repo. If a run dies, attach its output as input and set `RESUME_FROM`."""),
        code(f"!pip -q install -U \"transformers=={TRANSFORMERS_PIN}\" accelerate datasets huggingface_hub"),
        code(inline_cell(srcs, build_id)),
        md("## CONFIG"),
        code(f"""ARTIFACT_DIR = None   # only needed if the notebook says an artifacts dataset is required
CONFIG = dict(
    N_SENT={len(ids)},          # sentences (taken in order from the fixed id list)
    REPEATS=3,          # timed repeats per sentence and policy (median is reported)
    MAX_NEW=256,
    SMOKE=False,
    TARGET="meta-llama/Meta-Llama-3-8B-Instruct",
    DRAFT="meta-llama/Llama-3.2-1B-Instruct",
    MAX_MEMORY={{0: "8GiB", 1: "10GiB"}},
    OUT_ROOT="/kaggle/working",
    GIT_HASH=LGMTP_BUILD,
)
RESUME_FROM = None    # e.g. "/kaggle/input/<earlier-version-output>" to continue a dead run"""),
        code("import json\nSELECTED = json.loads(" + repr(json.dumps(selected, ensure_ascii=False)) + ")\n"
             f"IDS = {ids!r}\n" + pm_cell),
        code("""from huggingface_hub import login
try:
    from kaggle_secrets import UserSecretsClient
    login(UserSecretsClient().get_secret("HF_TOKEN"))
    print("Logged in with Kaggle secret HF_TOKEN")
except Exception as e:
    print(f"Kaggle secret HF_TOKEN not available ({e})")
    login()
import torch, transformers
print("torch", torch.__version__, "| transformers", transformers.__version__)"""),
        code("""import shutil
from pathlib import Path
if RESUME_FROM:   # copy partial outputs of a dead run back into place
    dst = Path(CONFIG["OUT_ROOT"]) / "real_loop"; dst.mkdir(parents=True, exist_ok=True)
    for f in Path(RESUME_FROM).rglob("*"):
        if f.is_file() and f.parent.name == "real_loop" and not (dst / f.name).exists():
            shutil.copy2(f, dst / f.name); print("resume: copied", f)
from lgmtp.spec_loop import notebook03_main
RESULT = notebook03_main(dict(CONFIG, SELECTED=SELECTED, IDS=IDS, PREFIX_MODEL_STATE=PREFIX_MODEL_STATE))"""),
    ]
    nb.metadata.update({"kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"},
                        "lgmtp_build": build_id})
    path = OUT / "03_real_loop.ipynb"
    nbf.write(nb, path)
    print("wrote", path, "|", build_id, f"| prefix model {len(pm_bytes) / 1e6:.2f} MB")
    return path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("which", choices=["01", "03"])
    a = ap.parse_args()
    if a.which == "01":
        build_01()
    else:
        build_03()


if __name__ == "__main__":
    main()
