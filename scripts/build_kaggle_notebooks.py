def git_hash() -> str:
    try:
        h = subprocess.check_output(["git", "rev-parse", "--short=12", "HEAD"], cwd=ROOT, text=True).strip()
        dirty = subprocess.check_output(["git", "status", "--porcelain", "--", "src", "scripts"],
                                        cwd=ROOT, text=True).strip()
        return h + ("-dirty" if dirty else "")
    except Exception:  # noqa: BLE001
        return "nogit"


def sources(names) -> dict[str, str]:
    return {n: (SRC / f"{n}.py").read_text(encoding="utf-8") for n in names}


def inline_cell(srcs: dict[str, str], build_id: str) -> str:
    lines = [
        "# === lgmtp source, generated by scripts/build_kaggle_notebooks.py: DO NOT EDIT ===",
        "import os, sys, importlib",
        "os.environ.setdefault('PYTORCH_CUDA_ALLOC_CONF', 'expandable_segments:True')",
        "PKG = '/kaggle/working/lgmtp' if os.path.isdir('/kaggle/working') else os.path.abspath('lgmtp')",
        "os.makedirs(PKG, exist_ok=True)",
        "LGMTP_SOURCES = {",
    ]
    for n, s in srcs.items():
        lines.append(f"    {n!r}: {s!r},")
    lines += [
        "}",
        "for _n, _s in LGMTP_SOURCES.items():",
        "    with open(os.path.join(PKG, _n + '.py'), 'w', encoding='utf-8') as _f:",
        "        _f.write(_s)",
        "sys.path.insert(0, os.path.dirname(PKG))",
        "for _m in [m for m in list(sys.modules) if m == 'lgmtp' or m.startswith('lgmtp.')]:",
        "    del sys.modules[_m]",
        "import lgmtp",
        f"LGMTP_BUILD = {build_id!r}",
        "print('lgmtp build', LGMTP_BUILD)",
    ]
    return "\n".join(lines)


